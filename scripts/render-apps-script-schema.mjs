import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(process.argv[2] || `${root}/config/sheet-schema.json`);
const outputPath = resolve(process.argv[3] || `${root}/apps-script/Schema.gs`);
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const body = `// Generated from config/sheet-schema.json. Do not edit this file by hand.\nconst INSTALL_SCHEMA = ${JSON.stringify(schema, null, 2)};\n`;
await writeFile(outputPath, body);
